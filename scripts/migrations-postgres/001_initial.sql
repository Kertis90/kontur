-- Начальная схема PostgreSQL соответствует выпущенным MySQL-миграциям 001–043.
-- Применяется только к новой установке. После выпуска этот файл неизменяем.
CREATE COLLATION kontur_text (provider=icu, locale='und-u-ks-level1', deterministic=false);

-- Обновляет служебную дату только при изменении строки, сохраняя явно заданную дату.
CREATE FUNCTION kontur_touch() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
  NEW.updated_at=date_trunc('second',statement_timestamp() AT TIME ZONE 'UTC');
 END IF;
 RETURN NEW;
END;
$$;

